export type UiLang = "en" | "hr";
const DICTS: Record<UiLang, Record<Key, string>> = { en, hr };

export type T = (key: Key | string, vars?: Record<string, string | number>) => string;

export function translator(lang: UiLang): T {
  return (key, vars) => {
    let s = DICTS[lang][key as Key] ?? en[key as Key] ?? key;
    for (const [k, v] of Object.entries(vars ?? {})) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

export const I18n = createContext<T>(translator("en"));
export const useT = () => useContext(I18n);
